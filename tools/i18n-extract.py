"""Lists every interface text in English, with its French text beside it, into app/src/main/resources/i18n/source.tsv.

Run from the repository root: python tools/i18n-extract.py
- L("en", "fr") pairs from app/, tv/ and core/ Kotlin sources, on one line or over several. Values written in the text ($name,
  ${expr}) become {1}, {2}... in order, the template form the catalogues use.
- Text entries of pc/i18n/Strings.kt, kept with their %s (they are formatted after translation).
A catalogue (i18n/<code>.tsv) holds `english<TAB>translation` lines keyed by the first column of this file.
"""
import glob
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STRING = r'"((?:[^"\\]|\\.)*)"'
# A trailing comma after the French text (L spread over several lines) is still a pair.
PAIR = re.compile(r'\bL\(\s*' + STRING + r'\s*,\s*' + STRING + r'\s*,?\s*\)', re.S)
TEMPLATE = re.compile(r'\$\{(?:[^{}]|\{[^{}]*\})*\}|\$[A-Za-z_][A-Za-z0-9_.]*(?:\(\))?')
TEXT = re.compile(r'Text\.(\w+) to ' + STRING)
# Pairs written outside L(), then passed to it or to Strings.pick as values: each pattern captures (english, french).
OTHER_PAIRS = [
    # RowBook: animeRow("id", "en", "fr", ...) and theme("id", "tag", "en", "fr")
    re.compile(r'\banimeRow\(\s*"[^"]*",\s*' + STRING + r',\s*' + STRING),
    re.compile(r'\btheme\(\s*"[^"]*",\s*"[^"]*",\s*' + STRING + r',\s*' + STRING + r'\s*\)'),
    # AnimeCatalog: theme("tag", "en", "fr") and row("key", "en", "fr", query)
    re.compile(r'\btheme\(\s*"[^"]*",\s*' + STRING + r',\s*' + STRING + r'\s*\)'),
    re.compile(r'\brow\(\s*"[^"]*",\s*' + STRING + r',\s*' + STRING + r',\s*AniQuery'),
    # Settings panes: NAME("id", Icons.Filled.X, "en", "fr", "summary en", "summary fr")
    re.compile(r'\b[A-Z_]+\("[a-z]+",\s*Icons\.Filled\.\w+,\s*' + STRING + r',\s*' + STRING + r',\s*' + STRING + r',\s*' + STRING + r'\)'),
    # AccentColor("id", 0xFF..., "en", "fr") and SubtitleFont("id", "en", "fr", vlcName)
    re.compile(r'\b[A-Z_]+\("[a-z]+",\s*0x[0-9A-Fa-f]+L?,\s*' + STRING + r',\s*' + STRING + r'\)'),
    re.compile(r'\b[A-Z_]+\("[a-z]+",\s*' + STRING + r',\s*' + STRING + r',\s*(?:null|"[^"]*")\)'),
]


def unescape(s: str) -> str:
    """Kotlin string escapes as the text reads at run time, except the values, which become {n}."""
    out, n = [], 0
    i = 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s):
            nxt = s[i + 1]
            # é is é at run time: the catalogue key must hold the character itself.
            if nxt == 'u' and re.fullmatch(r'[0-9a-fA-F]{4}', s[i + 2:i + 6]):
                out.append(chr(int(s[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append({'n': '\n', 't': '\t', '"': '"', '\\': '\\', '$': '\x00DOLLAR'}.get(nxt, nxt))
            i += 2
            continue
        m = TEMPLATE.match(s, i)
        if m:
            n += 1
            out.append('{%d}' % n)
            i = m.end()
            continue
        out.append(s[i])
        i += 1
    return ''.join(out).replace('\x00DOLLAR', '$')


def escape(s: str) -> str:
    return s.replace('\t', '\\t').replace('\n', '\\n')


def main() -> int:
    pairs = {}
    files = sorted(sum((glob.glob(str(ROOT / f'{module}/src/main/kotlin/**/*.kt'), recursive=True) for module in ('app', 'tv', 'core')), []))
    for f in files:
        source = Path(f).read_text(encoding='utf8')
        for m in PAIR.finditer(source):
            en, fr = unescape(m.group(1)), unescape(m.group(2))
            if en.strip():
                pairs.setdefault(en, fr)
        for pattern in OTHER_PAIRS:
            for m in pattern.finditer(source):
                groups = m.groups()
                for i in range(0, len(groups), 2):
                    en, fr = unescape(groups[i]), unescape(groups[i + 1])
                    if en.strip():
                        pairs.setdefault(en, fr)
    strings = (ROOT / 'core/src/main/kotlin/com/sokoul/pc/i18n/Strings.kt').read_text(encoding='utf8')
    english_block = strings[strings.index('val english'):strings.index('val french')]
    french_block = strings[strings.index('val french'):]
    french = {k: v for k, v in TEXT.findall(french_block)}
    for key, value in TEXT.findall(english_block):
        en = value.replace('\\"', '"').replace('\\n', '\n').replace('\\$', '$')
        fr = french.get(key, '').replace('\\"', '"').replace('\\n', '\n').replace('\\$', '$')
        pairs.setdefault(en, fr)
    out = ROOT / 'app/src/main/resources/i18n/source.tsv'
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ['# english<TAB>french — generated by tools/i18n-extract.py, do not edit']
    lines += [escape(en) + '\t' + escape(fr) for en, fr in sorted(pairs.items(), key=lambda p: p[0].lower())]
    out.write_text('\n'.join(lines) + '\n', encoding='utf8')
    print(f'{len(pairs)} texts, {sum("{1}" in en for en in pairs)} templates -> {out.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
