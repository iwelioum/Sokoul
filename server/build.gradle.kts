// The private Sokoul server: Ktor (Netty), one SQLite file, Cloudflare Access in front.
// openspec/changes/sokoul-server (design D1, D3, D4). Replaces API/ lot by lot.
plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.serialization)
    application
}

version = "0.1.0"

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    exclude("**/* - Copie.kt", "**/* - copy.kt")
}

kotlin {
    jvmToolchain(17)
}

application {
    mainClass.set("com.sokoul.server.MainKt")
}

// /health reports this version; the jar manifest carries it.
tasks.jar {
    manifest { attributes("Implementation-Version" to project.version) }
}

val generateServerVersion = tasks.register("generateServerVersion") {
    val out = layout.buildDirectory.dir("generated/serverVersion")
    val v = project.version.toString()
    inputs.property("version", v)
    outputs.dir(out)
    doLast {
        val file = out.get().file("com/sokoul/server/ServerVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText("package com.sokoul.server\n\n/** Generated by server/build.gradle.kts. */\nconst val SERVER_VERSION = \"$v\"\n")
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateServerVersion) }

dependencies {
    implementation(libs.ktor.server.core)
    implementation(libs.ktor.server.netty)
    implementation(libs.ktor.server.content.negotiation)
    implementation(libs.ktor.serialization.kotlinx.json)
    implementation(libs.ktor.server.status.pages)
    implementation(libs.ktor.server.call.logging)
    implementation(libs.sqlite.jdbc)
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.kotlinx.coroutines.core)
    // The credentials vault checks keys with the apps' own ServiceCheck (core), over OkHttp.
    implementation(project(":core"))
    implementation(libs.okhttp)
    runtimeOnly(libs.slf4j.simple)

    testImplementation(libs.junit)
    testImplementation(libs.ktor.server.test.host)
    testImplementation(libs.kotlinx.coroutines.test)
    testImplementation(libs.okhttp.mockwebserver)
    testRuntimeOnly(libs.slf4j.simple)
}
