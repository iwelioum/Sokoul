// SHA-256 and MD5 in plain JavaScript. crypto.subtle exists only on secure origins, and the server is also reached
// over plain HTTP on the LAN, so the two digests the client needs are computed here:
// - a profile code's digest (SHA-256 of "sokoul-profile:<salt>:<code>", as the apps compute it);
// - the account profile's UUID (Java's UUID.nameUUIDFromBytes, an MD5-based version 3 UUID).

const utf8 = (s) => new TextEncoder().encode(s);
const hex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');

